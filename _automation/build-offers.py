#!/usr/bin/env python3
"""
Build every affiliate offer listed in _automation/offers.json:

  go/<slug>/index.html      noindex bridge page (packages, label, guarantee)
  assets/cta-<key>.js       a.buy-link-<key>  ->  /go/<slug>/?s=&r=&c=
  assets/offer.js           the OFFERS block between the BUILD-OFFERS markers

Checkout links never carry the producer's `redirect` (or session) parameters.
Re-run after any change to offers.json:

  python3 _automation/build-offers.py
"""
import json, os, re

CFG = "_automation/offers.json"
offers = json.load(open(CFG))["offers"]

PAGE = open("_automation/offer-page.tpl.html").read()
CTA = open("assets/cta-mhny.js").read()


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") if s else s


def facts_html(o):
    if not o["facts"]:
        return ('<p><strong>Label not published.</strong> The manufacturer\'s order page does not show the '
                'supplement facts panel, so we don\'t list ingredients here. Check the label on the bottle '
                'before use.</p>')
    rows = "\n".join(f'      <tr><td>{esc(a)}</td><td>{esc(b)}</td></tr>' for a, b in o["facts"])
    img = ""
    if os.path.exists(f'assets/offer/{o["key"]}/label.webp'):
        from PIL import Image
        w, h = Image.open(f'assets/offer/{o["key"]}/label.webp').size
        img = (f'\n    <img class="label-img" src="/assets/offer/{o["key"]}/label.webp" width="{w}" '
               f'height="{h}" alt="{o["name"]} supplement facts label" loading="lazy">')
    return f'    <table class="facts">\n{rows}\n    </table>{img}'


def build_page(o):
    supply = {"capsule": "30", "gummy": "30", "liquid": "30"}
    f = {
        "key": o["key"], "slug": o["slug"], "name": o["name"], "headline": o["headline"],
        "intro": o["intro"], "serving": o["serving"], "count": o["count"],
        "facts": facts_html(o), "caution": o["caution"], "ship2": o["ship2"],
        "review": (f'<a href="/{o["slug"]}-review/">Read our independent {o["name"]} review</a>.'
                   if os.path.isdir(f'{o["slug"]}-review') else ""),
    }
    out = PAGE
    for k, v in f.items():
        out = out.replace("@@" + k + "@@", v)
    left = re.findall(r"@@(\w+)@@", out)
    if left:
        raise SystemExit(f'{o["slug"]}: unresolved {set(left)}')
    os.makedirs(f'go/{o["slug"]}', exist_ok=True)
    open(f'go/{o["slug"]}/index.html', "w").write(out)


def build_cta(o):
    c = CTA
    i = c.index("/* ="); j = c.index("*/", i) + 2
    head = (f'/* ============================================================================\n'
            f'   Memory Lab: {o["name"]} offer wiring (generated by _automation/build-offers.py)\n'
            f'     a.buy-link-{o["key"]} -> /go/{o["slug"]}/ ; checkout URLs live in assets/offer.js\n'
            f'   Subid shape: {o["key"]}_g_{{slug}}_p{{pack}}_r{{rank}}[_{{incoming}}]\n'
            f'   ============================================================================ */')
    c = c[:i] + head + c[j:]
    c = (c.replace("/go/memohoney/", f'/go/{o["slug"]}/')
          .replace("buy-link-mhny", f'buy-link-{o["key"]}')
          .replace("offer:'memohoney'", f"offer:'{o['slug']}'")
          .replace("'memohoney_offer'", f"'{o['slug']}_offer'"))
    if "memohoney" in c.lower() or "mhny" in c:
        raise SystemExit(f'{o["slug"]}: cta template still mentions MemoHoney')
    open(f'assets/cta-{o["key"]}.js', "w").write(c)


def build_offerjs():
    p = "assets/offer.js"
    s = open(p).read()
    blocks = []
    for o in offers:
        packs = ",\n".join(
            f'        "{n}": "https://buygoods.com/secure/checkout.html?aff_id={o["aff"]}&account_id={o["account"]}'
            f'&product_codename={o["codes"][n]}&subid={{clickid}}"' for n in ("2", "3", "6"))
        blocks.append(f'    // {o["name"]}: account_id {o["account"]} · aff_id {o["aff"]}\n'
                      f'    {o["key"]}: {{\n      tag: "{o["key"]}_g",\n      name: "{o["slug"]}",\n'
                      f'      packs: {{\n{packs}\n      }}\n    }}')
    gen = "    // BUILD-OFFERS:START (generated, edit _automation/offers.json)\n" + ",\n".join(blocks) + \
          "\n    // BUILD-OFFERS:END"
    if "BUILD-OFFERS:START" in s:
        s = re.sub(r"    // BUILD-OFFERS:START.*?// BUILD-OFFERS:END", lambda m: gen, s, flags=re.S)
    else:
        # first run: drop the hand-written vpc block, then append after mhny
        s = re.sub(r",\n    // VapoCept .*?\n    \}(?=\n  \};)", "", s, flags=re.S)
        s = s.replace("\n  };\n\n  var DEFAULT_PACK", ",\n" + gen + "\n  };\n\n  var DEFAULT_PACK", 1)
    open(p, "w").write(s)


for o in offers:
    build_page(o)
    build_cta(o)
    print(f'OK {o["slug"]:16} /go/{o["slug"]}/  cta-{o["key"]}.js')
build_offerjs()
print("offer.js updated")
